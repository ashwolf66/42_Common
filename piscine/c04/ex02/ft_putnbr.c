#include <unistd.h>

void	ft_putnbr(int nb)
{
	int		div;
	int		mod;
	char	nbc;

	div = nb / 10;
	mod = nb % 10;
	if (div != 0)
		ft_putnbr(div);
	if (mod < 0)
		mod *= -1;
	if (div == 0 && nb < 0)
		write(1, "-", 1);
	nbc = mod + '0';
	write(1, &nbc, 1);
}
