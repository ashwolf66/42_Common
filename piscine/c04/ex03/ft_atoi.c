int	ft_atoi(char *str)
{
	int	i;
	int	num;
	int	bu;

	i = 0;
	num = 0;
	bu = 0;
	while ((str[i] >= 9 && str[i] <= 13) || str[i] == 32)
		i++;
	while (str[i] == '-' || str[i] == '+')
	{
		if (str[i] == '-')
			bu++;
		i++;
	}
	while (str[i] != '\0' && (str[i] >= '0' && str[i] <= '9'))
	{
		num = num * 10 + (str[i] - '0');
		i++;
	}
	if (bu % 2 != 0)
		num *= -1;
	return (num);
}
