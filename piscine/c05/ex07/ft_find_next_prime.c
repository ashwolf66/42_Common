int	ft_is_prime(int nb)
{
	int	i;

	i = 2;
	if (nb <= 1)
		return (0);
	while (i < nb)
	{
		if (nb % i == 0)
			return (0);
		i++;
	}
	return (1);
}

int	ft_find_next_prime(int nb)
{
	int	num;

	num = 0;
	while (1)
	{
		num = ft_is_prime(nb);
		if (num == 1)
			return (nb);
		nb++;
	}
}
