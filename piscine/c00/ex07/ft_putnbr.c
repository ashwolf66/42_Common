#include <unistd.h>

void	ft_putnbr(int nb)
{
	char	nbc;

	if (nb == -2147483648)
	{
		write(1, "-2147483648", 11);
		return ;
	}
	if (nb < 0)
	{
		write(1, "-", 1);
		nb *= -1;
	}
	if (nb > 9)
	{
		ft_putnbr(nb / 10);
		nb %= 10;
	}
	if (nb < 10)
	{
		nbc = nb + '0';
		write(1, &nbc, 1);
	}
}
