#include "libft.h"

int	ft_atoi(const char *n)
{
	int	i;
	int	num;
	int	sign;

	i = 0;
	num = 0;
	sign = 1;
	while ((n[i] >= 9 && n[i] <= 13) || n[i] == 32)
		i++;
	if (n[i] == '+' || n[i] == '-')
	{
		if (n[i] == '-')
			sign = -1;
		i++;
	}
	while (n[i] == '0')
		i++;
	while (n[i] >= '0' && n[i] <= '9')
	{
		num = num * 10 + (n[i] - '0');
		i++;
	}
	if (n[i] != '\0')
		return (-1);
	return (num * sign);
}
